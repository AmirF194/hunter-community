TRANSLATORS = {
    "zeabur": translate_zeabur,
    "sealos": translate_sealos,
    "1panel": translate_1panel,
}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("platform", choices=sorted(TRANSLATORS))
    ap.add_argument("--out", required=True, help="输出目录")
    ap.add_argument("--web-port", type=int, default=3200, help="web 映射到宿主的端口（默认 3200，预发栈用）")
    ap.add_argument("--debug-ports", action="store_true", help="把内部服务端口也映出来（默认不映，与模板一致）")
    ap.add_argument("--seed", type=int, default=None, help="固定随机种子以复现（默认每次都是新的真随机）")
    ap.add_argument("--project", default=None,
                    help="compose 项目名（写进 name:）。默认 hunter-tpl-<平台>。"
                         "同时跑多套时**必须各给一个** —— 否则 `docker compose exec` "
                         "会按文件里的 name: 找到另一套，拿到别人的口令（M3 踩过）。")
    ap.add_argument("--tag", default=None,
                    help="把四个 hunter-community 镜像的标签换掉。**只给升级测试用** —— "
                         "先用老标签起一套、灌数据，再用新标签重新生成并 up -d，验证自动迁移与数据保留。"
                         "日常不要用：模板里钉的版本才是要发布的那一版。")
    args = ap.parse_args()

    rng = Rng(args.seed)
    compose, notes = TRANSLATORS[args.platform](rng, args.web_port, args.debug_ports)

    if args.project:
        compose["name"] = args.project

    if args.tag:
        n = 0
        for name, svc in compose["services"].items():
            img = svc.get("image", "")
            if "hunter-community-" in img and ":" in img:
                svc["image"] = img.rsplit(":", 1)[0] + ":" + args.tag
                n += 1
        notes.append(f"⚠ --tag {args.tag}：{n} 个自家镜像的标签被换掉（升级测试用，不是模板里的版本）")

    outdir = Path(args.out)
    outdir.mkdir(parents=True, exist_ok=True)
    header = (
        f"# 由 deploy/tools/template-to-compose.py 从 {args.platform} 模板自动翻译而来。\n"
        f"# ⚠️ 不要手工编辑 —— 要改就改模板再重新生成，否则测的就不是模板了。\n"
        f"# 重新生成：python3 deploy/tools/template-to-compose.py {args.platform} --out {args.out}\n"
    )
    (outdir / "docker-compose.yml").write_text(
        header + yaml.safe_dump(compose, allow_unicode=True, sort_keys=False, width=200),
        encoding="utf-8",
    )
    (outdir / "SECRETS.txt").write_text("\n".join(notes) + "\n", encoding="utf-8")

    print(f"✅ {args.platform} → {outdir/'docker-compose.yml'}")
    print(f"   服务 {len(compose['services'])} 个：{', '.join(compose['services'])}")
    for n in notes:
        print(f"   · {n}")
    print(f"\n真实密钥值不打印也不落盘明文说明，见容器环境变量。摘要写在 {outdir/'SECRETS.txt'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
